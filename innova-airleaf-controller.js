// INNOVA AirLeaf deviceType 002 -> Shelly Gen3.
// Stable controller for six existing Virtual Components.
// Version 5.0.1. See README.md for complete setup documentation.

// Change only HOST for a standard installation.
let HOST = "192.168.***.***";

let API = "http://" + HOST + "/api/v/1/";
let POLL_MS = 15000;
let HTTP_TIMEOUT_SEC = 5;
let WATCHDOG_MS = 8000;

// Virtual Component handles and HTTP queue state.
let V = {};
let jobs = [];
let activeJob = null;
let requestId = 0;
let activeRequestId = 0;
let watchdogTimer = null;

// Last valid INNOVA RESULT object.
let last = null;

function log(message) {
  console.log("[INNOVA] " + message);
}

// Avoid redundant Virtual Component writes and unnecessary change events.
function setValue(handle, value) {
  if (handle && handle.getValue() !== value) {
    handle.setValue(value);
  }
}

function setStatus(message) {
  message = String(message);

  if (message.length > 80) {
    message = message.slice(0, 80);
  }

  setValue(V.status, message);
}

// Ignore changes generated by this script while synchronizing device state.
function isInternal(event) {
  return event &&
    typeof event.source === "string" &&
    event.source.indexOf("script") === 0;
}

// Decode the INNOVA status fields and update the Shelly interface.
function applyStatus(status) {
  if (!status) return;

  last = status;

  // ps: power state, 1 = on.
  if (typeof status.ps === "number") {
    setValue(V.power, status.ps === 1);
  }

  // sp: temperature setpoint in tenths of a degree Celsius.
  if (typeof status.sp === "number") {
    setValue(V.setpoint, status.sp / 10);
  }

  // ta: measured room temperature in tenths of a degree Celsius.
  if (typeof status.ta === "number") {
    setValue(V.room, status.ta / 10);
  }

  // wm: working mode, 3 = heating and 5 = cooling.
  if (status.wm === 3) {
    setValue(V.mode, "heating");
  }

  if (status.wm === 5) {
    setValue(V.mode, "cooling");
  }

  // fn: fan function, 1=auto, 2=night, 3=min and 4=max.
  if (status.fn === 1) {
    setValue(V.fan, "auto");
  }

  if (status.fn === 2) {
    setValue(V.fan, "night");
  }

  if (status.fn === 3) {
    setValue(V.fan, "min");
  }

  if (status.fn === 4) {
    setValue(V.fan, "max");
  }
}

// Add a request to the serialized queue and start processing if idle.
function addJob(method, path, body, label, statusRequest) {
  if (jobs.length >= 6) {
    setStatus("error: command queue full");
    return;
  }

  jobs.push({
    method: method,
    path: path,
    body: body,
    label: label,
    statusRequest: statusRequest === true
  });

  nextJob();
}

// Recover when Shelly never delivers an HTTP callback.
function httpWatchdog() {
  if (activeJob === null) return;

  log(activeJob.label + " timeout");

  activeJob = null;
  activeRequestId = 0;
  watchdogTimer = null;
  jobs = [];

  setStatus("timeout: INNOVA " + HOST);
}

// Process both status responses and command acknowledgements.
function httpDone(
  result,
  errorCode,
  errorMessage,
  callbackRequestId
) {
  // Ignore a late callback from a request expired by the watchdog.
  if (
    callbackRequestId !== activeRequestId ||
    activeJob === null
  ) {
    return;
  }

  let job = activeJob;

  activeJob = null;
  activeRequestId = 0;

  if (watchdogTimer !== null) {
    Timer.clear(watchdogTimer);
    watchdogTimer = null;
  }

  if (
    errorCode !== 0 ||
    !result ||
    result.code !== 200
  ) {
    let message =
      errorMessage ||
      (
        "HTTP " +
        (result ? result.code : "no response")
      );

    log(job.label + " failed: " + message);
    setStatus("offline: " + message);
    nextJob();
    return;
  }

  let response;

  try {
    response = JSON.parse(result.body);
  } catch (error) {
    log(job.label + " invalid JSON");
    setStatus("error: invalid JSON");
    nextJob();
    return;
  }

  if (!response || response.success !== true) {
    log(job.label + " rejected");
    setStatus("error: rejected by INNOVA");
    nextJob();
    return;
  }

  if (job.statusRequest) {
    if (!response.RESULT) {
      setStatus("error: missing RESULT");
    } else if (
      String(response.deviceType) !== "002"
    ) {
      setStatus("error: device is not AirLeaf 002");
    } else {
      applyStatus(response.RESULT);
      setStatus("online / type 002");
    }
  } else {
    log(job.label + " accepted");

    // Confirm every command by reading the physical device again.
    addJob(
      "GET",
      "status",
      null,
      "status after command",
      true
    );
  }

  nextJob();
}

// Start the next queued request only when the previous one has completed.
function nextJob() {
  if (
    activeJob !== null ||
    jobs.length === 0
  ) {
    return;
  }

  activeJob = jobs[0];
  jobs = jobs.slice(1);

  requestId += 1;
  activeRequestId = requestId;

  watchdogTimer = Timer.set(
    WATCHDOG_MS,
    false,
    httpWatchdog
  );

  if (activeJob.method === "GET") {
    Shelly.call(
      "HTTP.GET",
      {
        url: API + activeJob.path,
        timeout: HTTP_TIMEOUT_SEC
      },
      httpDone,
      activeRequestId
    );
  } else {
    Shelly.call(
      "HTTP.POST",
      {
        url: API + activeJob.path,

        // INNOVA requires a body even for body-less POST commands.
        body:
          activeJob.body === null
            ? "{}"
            : activeJob.body,

        content_type: "application/json",
        timeout: HTTP_TIMEOUT_SEC
      },
      httpDone,
      activeRequestId
    );
  }
}

// Poll only when there are no active or waiting requests.
function poll() {
  if (
    activeJob === null &&
    jobs.length === 0
  ) {
    addJob(
      "GET",
      "status",
      null,
      "status",
      true
    );
  }
}

// Handle ON/OFF changes from Shelly UI, Cloud or another integration.
function powerChanged(event) {
  if (isInternal(event)) return;

  if (event.value === true) {
    addJob(
      "POST",
      "power/on",
      null,
      "power on",
      false
    );
  } else {
    addJob(
      "POST",
      "power/off",
      null,
      "power off",
      false
    );
  }
}

// Handle heating/cooling mode changes.
function modeChanged(event) {
  if (isInternal(event)) return;

  if (
    event.value !== "heating" &&
    event.value !== "cooling"
  ) {
    return;
  }

  // The unit must be on before its working mode can be changed.
  if (!last || last.ps !== 1) {
    addJob(
      "POST",
      "power/on",
      null,
      "power on before mode",
      false
    );
  }

  addJob(
    "POST",
    "set/mode/" + event.value,
    null,
    "mode " + event.value,
    false
  );
}

// Validate and send a temperature change.
function setpointChanged(event) {
  if (isInternal(event)) return;

  let temperature =
    Math.round(Number(event.value) * 2) / 2;

  if (
    temperature < 16 ||
    temperature > 31
  ) {
    if (last) {
      applyStatus(last);
    }

    return;
  }

  // INNOVA expects temperature in tenths of a degree Celsius.
  addJob(
    "POST",
    "set/setpoint",
    JSON.stringify({
      temp: Math.round(temperature * 10)
    }),
    "temperature " + String(temperature),
    false
  );
}

// Handle fan-function changes.
function fanChanged(event) {
  if (isInternal(event)) return;

  if (
    event.value !== "auto" &&
    event.value !== "night" &&
    event.value !== "min" &&
    event.value !== "max"
  ) {
    return;
  }

  addJob(
    "POST",
    "set/function/" + event.value,
    null,
    "fan " + event.value,
    false
  );
}

function start() {
  if (
    typeof Virtual === "undefined" ||
    typeof Virtual.getHandle !== "function"
  ) {
    log("ERROR: Virtual API unavailable");
    return;
  }

  // Stable component-key mapping. See README.md for exact configuration.
  V.power = Virtual.getHandle("boolean:200");
  V.mode = Virtual.getHandle("enum:201");
  V.setpoint = Virtual.getHandle("number:202");
  V.fan = Virtual.getHandle("enum:203");
  V.room = Virtual.getHandle("number:204");
  V.status = Virtual.getHandle("text:205");

  if (
    !V.power ||
    !V.mode ||
    !V.setpoint ||
    !V.fan ||
    !V.room ||
    !V.status
  ) {
    log("ERROR: Virtual Components 200-205 are missing");
    return;
  }

  // Room temperature and status are display-only, so they need no handlers.
  V.power.on("change", powerChanged);
  V.mode.on("change", modeChanged);
  V.setpoint.on("change", setpointChanged);
  V.fan.on("change", fanChanged);

  setStatus("connecting to " + HOST);

  poll();
  Timer.set(POLL_MS, true, poll);

  log("Controller v5.0.1 started for " + HOST);
}

start();
